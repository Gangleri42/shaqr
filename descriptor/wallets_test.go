	sizes2of3   = withSum("wsh(sortedmulti(2," + keyList(twoOfThreeKeys, multipath) + "))")
	sizes3of5   = withSum("wsh(sortedmulti(3," + keyList(fiveKeys, multipath) + "))")
	sizes10of20 = withSum("wsh(sortedmulti(10," + keyList(twentyKeys, multipath) + "))")
